import { printWithTitle } from "./lib/download.js";
import "./reader.css";

/**
 * "Save report as PDF" button for the search results page, plus a header that only appears
 * on the printed page (the query, the date and the not-legal-advice line).
 * Uses the browser's print dialog: choose "Save as PDF" as the destination.
 */
export default function PrintReport({ query, count }) {
  const date = new Date().toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });
  return (
    <>
      <button
        type="button"
        className="rd-btn pr-btn no-print"
        onClick={() => printWithTitle(`Section 10 search - ${query || "results"}`)}
      >
        Save report as PDF
      </button>
      <div className="print-only pr-head">
        <h1>Section 10 Divorce Search: report</h1>
        <p><strong>Query:</strong> {query}</p>
        <p><strong>Generated:</strong> {date}{typeof count === "number" ? ` · ${count} case${count === 1 ? "" : "s"} shown` : ""}</p>
        <p className="pr-warn">
          Built only from the cases shown. Not a success rate and not legal advice. Labels are generated by rules and
          may be wrong; check the judgment itself before relying on any of this.
        </p>
      </div>
    </>
  );
}
